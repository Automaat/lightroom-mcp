import { readFile, readdir, writeFile } from 'node:fs/promises';

const skillRoot = new URL('../../skills/raw-photo-lightroom-preset/', import.meta.url);
const files = ['SKILL.md', ...(await readdir(new URL('references/', skillRoot)))
  .sort().map((name) => `references/${name}`)];
const sections = await Promise.all(files.map(async (file) =>
  `# ${file}\n\n${(await readFile(new URL(file, skillRoot), 'utf8')).replace(/\r\n/g, '\n')}`));
const text = sections.join('\n\n').trim();
await writeFile(new URL('../src/skill-content.ts', import.meta.url),
  `// Generated by scripts/generate-skill.mjs.\nexport const SKILL_TEXT = ${JSON.stringify(text)};\n`);

const manifestUrl = new URL('../../mcpb/manifest.json', import.meta.url);
const manifest = JSON.parse(await readFile(manifestUrl, 'utf8'));
const prompt = manifest.prompts?.find((entry) => entry.name === 'raw-photo-lightroom-preset');
if (!prompt) {
  throw new Error('mcpb/manifest.json does not declare the raw-photo-lightroom-preset prompt');
}
prompt.text = text;
await writeFile(manifestUrl, `${JSON.stringify(manifest, null, 2)}\n`);
