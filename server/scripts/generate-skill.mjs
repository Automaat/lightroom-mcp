import { readFile, readdir, writeFile } from 'node:fs/promises';

const skillRoot = new URL('../../skills/raw-photo-lightroom-preset/', import.meta.url);
const files = ['SKILL.md', ...(await readdir(new URL('references/', skillRoot)))
  .sort().map((name) => `references/${name}`)];
const sections = await Promise.all(files.map(async (file) =>
  `# ${file}\n\n${await readFile(new URL(file, skillRoot), 'utf8')}`));
await writeFile(new URL('../src/skill-content.ts', import.meta.url),
  `// Generated by scripts/generate-skill.mjs.\nexport const SKILL_TEXT = ${JSON.stringify(sections.join('\n\n'))};\n`);
