local TO_NFC = {}
for composed, decomposed in pairs(TO_NFD) do
    TO_NFC[decomposed] = composed
end

local UTF8_CHARACTER = "[%z\1-\127\194-\244][\128-\191]*"
local MARK_LEAD_BYTES = { ["\204"] = true, ["\205"] = true }
local KANA_MARKS = { ["\227\130\153"] = true, ["\227\130\154"] = true }

local function isMark(character)
    return KANA_MARKS[character] or (#character == 2 and MARK_LEAD_BYTES[character:sub(1, 1)])
end

function PathForms.isAscii(path)
    return not path:find("[\128-\255]")
end

function PathForms.toNfd(path)
    return (path:gsub(UTF8_CHARACTER, TO_NFD))
end

function PathForms.toNfc(path)
    local parts = {}
    local base, marks = "", ""
    local function flush()
        if base ~= "" or marks ~= "" then
            parts[#parts + 1] = TO_NFC[base .. marks] or (base .. marks)
        end
    end
    for character in PathForms.toNfd(path):gmatch(UTF8_CHARACTER) do
        if isMark(character) then
            marks = marks .. character
        else
            flush()
            base, marks = character, ""
        end
    end
    flush()
    return table.concat(parts)
end

function PathForms.same(left, right)
    return left == right or PathForms.toNfd(left) == PathForms.toNfd(right)
end

return PathForms
